//! The desktop's clipboard, and its history.

use std::sync::Arc;

use tokio::sync::watch;
use wado_protocol::ClipEntry;

use crate::{Fut, Res};

/// Clipboard contents: a mime type and the bytes. Shared, so a copy crossing between the session
/// and the desktop is never duplicated. Empty `data` is nothing copied yet.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Clip {
    pub mime: String,
    pub data: Arc<[u8]>,
    /// The app that copied it marked it a secret — a password manager's copy ([`is_secret`]).
    /// Set on this side, it is offered with the same mark, so the desktop's own clipboard
    /// managers skip it too.
    pub secret: bool,
}

/// What a text selection is offered as, best first.
pub const TEXT: &[&str] = &[
    "text/plain;charset=utf-8",
    "text/plain",
    "UTF8_STRING",
    "TEXT",
    "STRING",
];

/// The type a secret is marked with when this side offers one, and the value it is served as —
/// KDE's convention, which KeePassXC, Bitwarden, GPaste and `wl-copy --sensitive` all speak.
pub const SECRET_HINT: (&str, &[u8]) = ("x-kde-passwordManagerHint", b"secret");

/// The extra types password managers offer beside a secret, matched without regard to case:
///
/// - `x-kde-passwordManagerHint` (value `secret`) — KDE's; set by KeePassXC, Bitwarden desktop
///   (through `arboard`'s exclude-from-history), 1Password, GPaste and `wl-copy --sensitive`.
/// - `org.nspasteboard.ConcealedType` / `TransientType` / `AutoGeneratedType` — the
///   nspasteboard.org markers macOS managers use, which cross-platform apps also offer.
/// - `ExcludeClipboardContentFromMonitorProcessing`, `CanIncludeInClipboardHistory`,
///   `CanUploadToCloudClipboard` — Windows' markers, which Chromium and Electron apps also set.
///
/// The value is not read: a type that only a password manager would offer is mark enough, and a
/// copy wrongly held back costs less than a password wrongly sent.
pub const SECRET_TYPES: &[&str] = &[
    "x-kde-passwordmanagerhint",
    "org.nspasteboard.concealedtype",
    "org.nspasteboard.transienttype",
    "org.nspasteboard.autogeneratedtype",
    "application/x-nspasteboard-concealed-type",
    "excludeclipboardcontentfrommonitorprocessing",
    "canincludeinclipboardhistory",
    "canuploadtocloudclipboard",
];

/// Do the offered `types` mark the copy a secret?
pub fn is_secret<S: AsRef<str>>(types: &[S]) -> bool {
    types.iter().any(|t| {
        let t = t.as_ref().trim().to_ascii_lowercase();
        SECRET_TYPES.contains(&t.as_str())
    })
}

impl Clip {
    pub fn is_text(&self) -> bool {
        self.mime.starts_with("text/") || TEXT.contains(&self.mime.as_str())
    }
}

/// The desktop's clipboard.
pub trait Clipboard: Send + Sync {
    /// What is on it now: text if offered, else the first image type — with `secret` set when a
    /// password manager marked it so.
    fn get(&self) -> Fut<'_, Res<Clip>>;
    /// Make `clip` the clipboard; a `secret` one is offered with [`SECRET_HINT`].
    fn set(&self, clip: Clip) -> Fut<'_, Res<()>>;
    /// Ticks once per change on the desktop (a change this side made included).
    fn changes(&self) -> watch::Receiver<u64>;
}

/// The desktop's clipboard history, newest first, pinned entries on top. An `id` is the
/// provider's and is checked by it before use.
pub trait ClipHistory: Send + Sync {
    fn list(&self) -> Fut<'_, Res<Vec<ClipEntry>>>;
    fn get(&self, id: String) -> Fut<'_, Res<Clip>>;
    fn delete(&self, id: String) -> Fut<'_, Res<()>>;
    fn pin(&self, id: String, on: bool) -> Fut<'_, Res<()>>;
}

#[cfg(test)]
mod tests {
    use super::*;

    /// What each password manager offers beside a password it copies, as seen with
    /// `wl-paste --list-types` — and two ordinary copies that must not count.
    #[test]
    fn password_managers_are_recognised() {
        let keepassxc = ["text/plain", "x-kde-passwordManagerHint"];
        let bitwarden = [
            "text/plain;charset=utf-8",
            "UTF8_STRING",
            "x-kde-passwordManagerHint",
        ];
        let one_password = [
            "text/plain;charset=utf-8",
            "x-kde-passwordManagerHint",
            "ExcludeClipboardContentFromMonitorProcessing",
        ];
        let chromium = ["text/plain", "CanIncludeInClipboardHistory"];
        let mac_style = ["text/plain", "org.nspasteboard.ConcealedType"];
        for types in [
            &keepassxc[..],
            &bitwarden[..],
            &one_password[..],
            &chromium[..],
            &mac_style[..],
        ] {
            assert!(is_secret(types), "{types:?}");
        }
        let firefox = ["text/html", "text/plain;charset=utf-8", "UTF8_STRING"];
        let screenshot = ["image/png"];
        assert!(!is_secret(&firefox));
        assert!(!is_secret(&screenshot));
        assert!(
            is_secret(&[SECRET_HINT.0]),
            "what this side marks, it reads"
        );
    }
}
