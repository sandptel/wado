// The app's OS logos (A7 in docs/superpowers/plans/2026-10-30-native-android.md): one monochrome
// VectorDrawable per slug the core can name (crates/client-core/src/os_logo.rs), from a pinned
// Simple Icons release, tinted at draw time with a base16 role (no brand colours).
//
//   node scripts/os-logos.mjs        (needs network for `npm pack`)
//
// Writes android/app/src/main/res/drawable/os_<slug>.xml and
// android/app/src/main/assets/licenses/os-logos.txt (title, source and brand guidelines per logo,
// shown on About). Fails if a slug is missing from the release, or if any icon's `license` is set
// to anything but CC0 — the logos are used only to name the computer's OS (nominative use),
// unmodified in shape and never as wado's own mark.

import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";

const PIN = "16.36.0";
const ALLOWED = new Set(["CC0-1.0"]);
const ROOT = new URL("..", import.meta.url).pathname;
const DRAW = join(ROOT, "android/app/src/main/res/drawable");
const LIC = join(ROOT, "android/app/src/main/assets/licenses");

const src = readFileSync(join(ROOT, "crates/client-core/src/os_logo.rs"), "utf8");
const table = src.slice(src.indexOf("const IDS"), src.indexOf("];"));
const slugs = [...new Set([...table.matchAll(/\("[^"]+",\s*"([^"]+)"\)/g)].map((m) => m[1]).concat(["linux"]))].sort();

const tmp = mkdtempSync(join(tmpdir(), "wado-os-logos-"));
let failed = 0;
try {
  execFileSync("npm", ["pack", `simple-icons@${PIN}`, "--pack-destination", tmp, "--silent"], { stdio: ["ignore", "ignore", "inherit"] });
  execFileSync("tar", ["xzf", join(tmp, `simple-icons-${PIN}.tgz`), "-C", tmp]);
  const data = JSON.parse(readFileSync(join(tmp, "package/data/simple-icons.json"), "utf8"));
  mkdirSync(DRAW, { recursive: true });
  mkdirSync(LIC, { recursive: true });
  const notes = [
    `OS logos from Simple Icons ${PIN} (https://simpleicons.org), CC0-1.0.`,
    "Each mark belongs to its owner; wado shows it only to name the operating system a computer runs.",
    "",
  ];
  for (const slug of slugs) {
    const e = data.find((x) => x.slug === slug);
    if (!e) { console.error(`missing from simple-icons ${PIN}: ${slug}`); failed++; continue; }
    if (e.license && !ALLOWED.has(e.license.type)) {
      console.error(`${slug}: licence ${e.license.type} is not CC0 — drop it from os_logo.rs`);
      failed++;
      continue;
    }
    const svg = readFileSync(join(tmp, `package/icons/${slug}.svg`), "utf8");
    const paths = [...svg.matchAll(/<path[^>]* d="([^"]+)"/g)].map((m) => m[1]);
    if (paths.length === 0) { console.error(`${slug}: no path data`); failed++; continue; }
    const xml = [
      "<?xml version=\"1.0\" encoding=\"utf-8\"?>",
      `<!-- ${e.title}: Simple Icons ${PIN}, CC0-1.0. Generated by scripts/os-logos.mjs; do not edit. -->`,
      "<vector xmlns:android=\"http://schemas.android.com/apk/res/android\"",
      "    android:width=\"24dp\" android:height=\"24dp\"",
      "    android:viewportWidth=\"24\" android:viewportHeight=\"24\">",
      ...paths.map((d) => `    <path android:fillColor="@android:color/white" android:pathData="${d}" />`),
      "</vector>",
      "",
    ].join("\n");
    writeFileSync(join(DRAW, `os_${slug}.xml`), xml);
    notes.push(`${e.title} (${slug})`, `  source: ${e.source}`, `  guidelines: ${e.guidelines || "none published"}`, "");
  }
  writeFileSync(join(LIC, "os-logos.txt"), notes.join("\n"));
} finally {
  rmSync(tmp, { recursive: true, force: true });
}
if (failed) { console.error(`${failed} logo(s) failed`); process.exit(1); }
console.log(`${slugs.length} logos written to ${DRAW}`);
